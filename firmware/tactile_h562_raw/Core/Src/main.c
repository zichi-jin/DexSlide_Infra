static void Usart2UsbBridge_StartRxDma(void)
{
  if (HAL_UARTEx_ReceiveToIdle_DMA(&huart2,
                                   g_usart2_rx_dma_buffer,
                                   sizeof(g_usart2_rx_dma_buffer)) != HAL_OK)
  {
    Error_Handler();
  }

  /* RX half-transfer events are unnecessary; IDLE or a full buffer ends a chunk. */
  __HAL_DMA_DISABLE_IT(huart2.hdmarx, DMA_IT_HT);
}

static void Usart2UsbBridge_ProcessHostData(void)
{
  UCHAR data[CDC_BRIDGE_RX_BURST_SIZE];
  ULONG actual_length = 0U;

  if (USBD_CDC_ACM_IsReady() != UX_TRUE)
  {
    return;
  }

  for (;;)
  {
    if ((USBD_CDC_ACM_Read(data, (ULONG)sizeof(data), &actual_length) != UX_SUCCESS) || (actual_length == 0U))
    {
      break;
    }

    (void)HAL_UART_Transmit(&huart2, data, (uint16_t)actual_length, CDC_BRIDGE_TX_TIMEOUT_MS);

    if (actual_length < (ULONG)sizeof(data))
    {
      break;
    }
  }
}

void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t size)
{
  if ((huart->Instance == USART2) && (size > 0U))
  {
    /* Copy exactly the bytes DMA received. No protocol parsing or framing occurs here. */
    (void)USBD_CDC_ACM_Write(g_usart2_rx_dma_buffer, (ULONG)size);
  }

  if (huart->Instance == USART2)
  {
    Usart2UsbBridge_StartRxDma();
  }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART2)
  {
    __HAL_UART_CLEAR_FLAG(huart, UART_CLEAR_OREF | UART_CLEAR_NEF | UART_CLEAR_FEF | UART_CLEAR_PEF);
    Usart2UsbBridge_StartRxDma();
  }
}

